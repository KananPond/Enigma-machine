"""English language model: scoring, word segmentation and punctuation.

An Enigma machine only ever sees letters.  Spaces and punctuation are thrown
away before the message goes in, so decoding has two halves: running the
cipher backwards, and putting the lost structure back.

This module holds the statistics that make the second half possible.

* :meth:`EnglishModel.score` rates how English a letter string looks.  It is
  the mean log probability of the string's quadgrams and is used to judge
  candidate decryptions - for example while an unknown plugboard is searched.
* :meth:`EnglishModel.segment` splits a letter string into words with a
  dynamic program over the embedded vocabulary.
* :meth:`EnglishModel.restore_spaces` picks the better of the two ways to
  find the word boundaries: the ``X``/``Q`` space substitutes that the
  message preparation may have used, and the dictionary segmentation.
* :meth:`EnglishModel.restore_punctuation` adds sentence punctuation and
  capitalisation.

The statistics themselves live in :mod:`enigma.english_data` and are
generated by ``tools/build_english_model.py`` from public domain sources.
"""

from __future__ import annotations

import math

from .data import ALPHABET
from .english_data import (
    BIGRAM_COUNTS,
    BIGRAM_TOTAL,
    LETTER_FREQ,
    QUADGRAM_COUNTS,
    QUADGRAM_TOTAL,
    WORD_COUNTS,
    WORDS,
)

#: The character that stands for a space in the n-gram tables.
SPACE = " "

#: The longest word the segmenter will look for.
MAX_WORD_LENGTH = 24

#: Log probability assigned to every letter of a word that is not in the
#: vocabulary.
UNKNOWN_LETTER_LOGP = -3.5

#: The longest run of unknown letters the segmenter considers to be one word.
MAX_UNKNOWN_RUN = 15

#: Words that open a sentence almost every time they show up: pronouns,
#: question words and a few deictics.
STRONG_STARTERS = frozenset(
    """
    I WE YOU HE SHE IT THEY THERE HERE
    WHO WHAT WHERE WHY HOW WHICH WHOM WHOSE
    """.split()
)

#: Words that open a sentence only now and then.  "THE" for instance is
#: usually just an article, so a sentence break in front of it has to be
#: earned.
WEAK_STARTERS = frozenset(
    """
    A AN THE THIS THAT THESE THOSE
    MY OUR YOUR HIS HER ITS THEIR
    ONE TWO THREE FOUR ALL EVERY NO YES MANY MOST SOME SUCH
    IF WHEN WHILE AFTER BEFORE UNLESS UNTIL
    NONE EITHER NEITHER BOTH FEW SEVERAL
    """.split()
)

#: Words after which a sentence break is unlikely.
NO_BREAK_AFTER = frozenset(
    """
    A AN THE OF IN ON AT TO FOR WITH FROM BY AND OR BUT NOR SO IF AS
    THAT THAN IS ARE WAS WERE BE BEEN BEING AM ITS MY OUR YOUR HIS HER
    THEIR WHICH WHO WHOM WHOSE WHETHER WHILE WHEN WHERE WHY HOW
    NOT NO VERY TOO ALSO JUST ONLY EVEN STILL YET HAS HAVE HAD
    DO DOES DID WILL WOULD CAN COULD SHOULD MUST MAY MIGHT SHALL
    INTO OVER UNDER ABOUT BETWEEN THROUGH DURING WITHOUT WITHIN
    """.split()
)

#: Words that end a sentence by themselves.
SENTENCE_ENDERS = frozenset(("STOP", "END"))

#: A sentence with at least this many words is long enough that a missing
#: break in front of a weak sentence starter is worth guessing.
LONG_SENTENCE = 12

#: Words that turn a sentence into a question.
QUESTION_STARTERS = frozenset(
    """
    WHO WHAT WHERE WHEN WHY HOW WHICH DO DOES DID IS ARE AM CAN
    WILL WOULD COULD SHOULD HAVE HAS MAY MIGHT
    """.split()
)


class EnglishModel:
    """Statistics of English, used to read a decryption.

    The model is immutable and safe to share.  :data:`DEFAULT_MODEL` is the
    instance built from the embedded tables.
    """

    def __init__(self) -> None:
        self._letter_logp = [math.log10(max(frequency, 1e-9)) for frequency in LETTER_FREQ]
        self._bigram_total = max(BIGRAM_TOTAL, 1)
        self._quadgram_total = max(QUADGRAM_TOTAL, 1)
        self._bigram_logp = {
            key: math.log10(value / self._bigram_total) for key, value in BIGRAM_COUNTS.items()
        }
        self._quadgram_logp = {
            key: math.log10(value / self._quadgram_total)
            for key, value in QUADGRAM_COUNTS.items()
        }
        # An n-gram that is not in the table is very unlikely, so it gets a
        # floor one decade below "seen exactly once".
        self._bigram_floor = math.log10(1.0 / self._bigram_total) - 1.0
        self._quadgram_floor = math.log10(1.0 / self._quadgram_total) - 1.0

        words = WORDS.split()
        counts = [int(value) for value in WORD_COUNTS.split()]
        total = max(sum(counts), 1)
        # The vocabulary is lower case, the texts are upper case.
        self._word_logp = {
            word.upper(): math.log10(count / total)
            for word, count in zip(words, counts)
        }
        self._max_word_length = min(MAX_WORD_LENGTH, max(len(word) for word in words))

    # ------------------------------------------------------------- helpers
    @staticmethod
    def letters(text: str) -> str:
        """Return only the letters of *text*, upper cased."""
        return "".join(character for character in text.upper() if character in ALPHABET)

    def letter_logp(self, letter: str) -> float:
        """Return the log probability of a single letter."""
        return self._letter_logp[ALPHABET.index(letter.upper())]

    def bigram_logp(self, first: str, second: str) -> float:
        """Return the log probability of two letters, optionally around a space."""
        key = first.upper() + second.upper()
        return self._bigram_logp.get(key, self._bigram_floor)

    def quadgram_logp(self, quadgram: str) -> float:
        """Return the log probability of four letters."""
        return self._quadgram_logp.get(quadgram.upper(), self._quadgram_floor)

    def word_logp(self, word: str) -> float:
        """Return the log probability of a word of the vocabulary."""
        return self._word_logp.get(word.upper(), UNKNOWN_LETTER_LOGP * max(len(word), 1))

    def is_word(self, word: str) -> bool:
        """Return ``True`` when *word* is part of the vocabulary."""
        return word.upper() in self._word_logp

    @property
    def quadgram_table(self) -> dict[str, float]:
        """The log probabilities of the known quadgrams."""
        return self._quadgram_logp

    @property
    def quadgram_floor(self) -> float:
        """The log probability used for quadgrams that are not in the table."""
        return self._quadgram_floor

    # ------------------------------------------------------------- scoring
    def score(self, text: str) -> float:
        """Rate how English the letter string *text* looks.

        The result is the mean log probability of its quadgrams: roughly
        ``-2.5`` for English, ``-3.5`` for random letters.  Higher is better.
        """
        letters = self.letters(text)
        if len(letters) < 4:
            if not letters:
                return self._bigram_floor
            return sum(self.letter_logp(letter) for letter in letters) / len(letters)
        total = 0.0
        for index in range(len(letters) - 3):
            total += self.quadgram_logp(letters[index : index + 4])
        return total / (len(letters) - 3)

    def word_coverage(self, text: str) -> float:
        """Return the share of letters that belong to known words."""
        letters = self.letters(text)
        if not letters:
            return 0.0
        covered = 0
        for token in self.segment(letters):
            if self.is_word(token):
                covered += len(token)
        return covered / len(letters)

    # -------------------------------------------------------- segmentation
    def token_score(self, token: str) -> float:
        """Return the score of one word of a segmentation.

        A word of the vocabulary is worth its own frequency.  A run of
        letters that is not in the vocabulary is scored by its letter pairs
        and a penalty per letter - so the two kinds of words can be compared
        with each other.
        """
        if self.is_word(token):
            return self._word_logp[token]
        total = UNKNOWN_LETTER_LOGP * len(token)
        for index in range(len(token) - 1):
            total += self.bigram_logp(token[index], token[index + 1])
        return total

    def boundary_score(self, previous: str, following: str) -> float:
        """Return the score of putting a space between two words."""
        return self.bigram_logp(previous, SPACE) + self.bigram_logp(SPACE, following)

    def segment(self, text: str) -> list[str]:
        """Split the letter string *text* into words.

        A dynamic program over the vocabulary.  At every position the best
        continuation is either a word of the vocabulary or a run of letters
        that is not; both are scored on the same scale, so the segmenter
        always prefers real words.
        """
        letters = self.letters(text)
        count = len(letters)
        if count == 0:
            return []

        best = [float("-inf")] * (count + 1)
        back: list[tuple[int, str] | None] = [None] * (count + 1)
        best[0] = 0.0

        for start in range(count):
            if best[start] == float("-inf"):
                continue
            previous = letters[start - 1] if start > 0 else ""
            lead = 0.0
            if start > 0:
                lead = self.bigram_logp(previous, SPACE)

            # A word of the vocabulary.
            limit = min(self._max_word_length, count - start)
            for length in range(1, limit + 1):
                word = letters[start : start + length]
                word_p = self._word_logp.get(word)
                if word_p is None:
                    continue
                score = best[start] + word_p + lead
                if start > 0:
                    score += self.bigram_logp(SPACE, word[0])
                end = start + length
                if score > best[end]:
                    best[end] = score
                    back[end] = (start, word)

            # A run of letters that is not in the vocabulary.
            run = 0.0
            for length in range(1, min(MAX_UNKNOWN_RUN, count - start) + 1):
                if length > 1:
                    run += self.bigram_logp(
                        letters[start + length - 2], letters[start + length - 1]
                    )
                score = best[start] + UNKNOWN_LETTER_LOGP * length + run + lead
                if start > 0:
                    score += self.bigram_logp(SPACE, letters[start])
                end = start + length
                if score > best[end]:
                    best[end] = score
                    back[end] = (start, letters[start:end])

        tokens: list[str] = []
        index = count
        while index > 0:
            entry = back[index]
            if entry is None:  # pragma: no cover - the letter run always wins
                tokens.append(letters[index - 1])
                index -= 1
                continue
            start, token = entry
            tokens.append(token)
            index = start
        tokens.reverse()
        return tokens

    def segment_with_marker(self, text: str, marker: str) -> list[str]:
        """Segment *text* under the assumption that *marker* marks the spaces.

        The words are separated by the marker, but a word may contain the
        marker itself - ``FOX`` ends with an ``X`` - as long as what follows
        it is a marker again.  That is the difference to a plain split: the
        marker is a separator only where the words need one.
        """
        letters = self.letters(text)
        count = len(letters)
        if count == 0:
            return []

        best = [float("-inf")] * (count + 1)
        back: list[tuple[int, str] | None] = [None] * (count + 1)
        best[0] = 0.0

        for start in range(count):
            if best[start] == float("-inf"):
                continue
            previous = letters[start - 1] if start > 0 else ""

            if letters[start] == marker and start == count - 1:
                # A marker at the very end is a trailing separator.
                if best[start] > best[count]:
                    best[count] = best[start]
                    back[count] = (start, "")
                continue

            limit = min(self._max_word_length, count - start)
            for length in range(1, limit + 1):
                word = letters[start : start + length]
                word_p = self._word_logp.get(word)
                if word_p is None:
                    continue
                end = start + length
                if end < count and letters[end] != marker:
                    continue
                score = best[start] + word_p
                if start > 0:
                    score += self.boundary_score(previous, word[0])
                nxt = end + 1 if end < count else end
                if score > best[nxt]:
                    best[nxt] = score
                    back[nxt] = (start, word)

            # A run of letters that is not in the vocabulary.
            end = start
            while end < count and letters[end] != marker:
                end += 1
            if end > start:
                run = letters[start:end]
                score = best[start] + self.token_score(run)
                if start > 0:
                    score += self.boundary_score(previous, run[0])
                nxt = end + 1 if end < count else end
                if score > best[nxt]:
                    best[nxt] = score
                    back[nxt] = (start, run)

        tokens: list[str] = []
        index = count
        while index > 0:
            entry = back[index]
            if entry is None:  # pragma: no cover - the letter run always wins
                tokens.append(letters[index - 1])
                index -= 1
                continue
            start, token = entry
            if token:
                tokens.append(token)
            index = start
        tokens.reverse()
        return tokens

    def segmentation_score(self, tokens: list[str]) -> float:
        """Return the score of a list of words.

        The score is the log probability of the whole letter stream with the
        spaces put in: every word pays for itself and every word boundary
        pays for the space.  Candidates are compared with it, so a
        segmentation cannot win by cutting the text into more and more short
        pieces.
        """
        if not tokens:
            return self._bigram_floor
        total = 0.0
        for index, token in enumerate(tokens):
            total += self.token_score(token)
            if index + 1 < len(tokens):
                total += self.boundary_score(token[-1], tokens[index + 1][0])
        return total

    def restore_spaces(self, text: str) -> str:
        """Put the word boundaries back into the letter string *text*.

        Two hypotheses are compared and the better one is used:

        1. The message preparation replaced spaces with ``X`` or ``Q``, so
           those letters mark the word boundaries.
        2. The words have to be recovered with the dictionary segmenter.
        """
        return " ".join(self.restore_spaces_tokens(text))

    def restore_spaces_tokens(self, text: str) -> list[str]:
        """Like :meth:`restore_spaces`, but returns the words separately.

        Three candidates are compared:

        1. The dictionary segmenter, which treats every letter - including
           an ``X`` or a ``Q`` - as part of a word.
        2. The same segmenter under the assumption that the ``X`` marks the
           spaces.
        3. The same under the assumption that the ``Q`` marks the spaces.

        The message preparation marks the spaces with ``X`` or ``Q``, so
        those letters are the most reliable word boundaries there are - but
        they can also be ordinary letters, and only the language model can
        tell the two apart.
        """
        letters = self.letters(text)
        if not letters:
            return []

        candidates: list[list[str]] = [self.segment(letters)]
        for marker in ("X", "Q"):
            if marker in letters:
                candidates.append(self.segment_with_marker(letters, marker))

        return max(candidates, key=self.segmentation_score)

    # ---------------------------------------------------------- punctuation
    def restore_punctuation(self, text: str) -> str:
        """Add sentence punctuation and capitalisation to *text*.

        The Enigma never saw any punctuation, so it can only be guessed: a
        sentence is assumed to start before a word that commonly opens one,
        unless the previous word is one that usually continues a sentence.
        """
        words = text.split()
        if not words:
            return ""

        result: list[str] = []
        sentence_start = True
        sentence_length = 0
        sentence_first = ""

        for index, word in enumerate(words):
            upper = word.upper()
            if sentence_start:
                word = word[:1].upper() + word[1:]
                sentence_first = upper
            if upper == "I":
                word = "I"
            result.append(word)
            sentence_length += 1

            if index + 1 < len(words):
                following = words[index + 1].upper()
                if self._starts_sentence(upper, following, sentence_length):
                    result[-1] += self._terminator(sentence_first)
                    sentence_start = True
                    sentence_length = 0
                else:
                    sentence_start = False
            else:
                result[-1] += self._terminator(sentence_first)
                sentence_start = False

        return " ".join(result)

    @staticmethod
    def _terminator(sentence_first: str) -> str:
        """Return the punctuation that ends a sentence."""
        return "?" if sentence_first in QUESTION_STARTERS else "."

    @staticmethod
    def _starts_sentence(previous: str, following: str, sentence_length: int) -> bool:
        """Return ``True`` when a sentence most likely starts at *following*.

        *sentence_length* is the number of words of the sentence so far.
        """
        if previous in SENTENCE_ENDERS:
            return True
        if previous in NO_BREAK_AFTER:
            return False
        if following in STRONG_STARTERS:
            return True
        if following in WEAK_STARTERS:
            # A weak starter only gets a break when the word before it could
            # end a sentence - a verb, most of the time - or when the
            # sentence has run on for a long time.
            if previous.endswith("ED") or previous.endswith("S"):
                return True
            return sentence_length >= LONG_SENTENCE
        return False

    def restore(self, text: str) -> str:
        """Restore both the word boundaries and the punctuation of *text*."""
        return self.restore_punctuation(self.restore_spaces(text))


#: The model built from the embedded tables.
DEFAULT_MODEL = EnglishModel()


def score_text(text: str) -> float:
    """Rate how English the letter string *text* looks."""
    return DEFAULT_MODEL.score(text)


def restore_spaces(text: str) -> str:
    """Put the word boundaries back into the letter string *text*."""
    return DEFAULT_MODEL.restore_spaces(text)


def restore_punctuation(text: str) -> str:
    """Add sentence punctuation and capitalisation to *text*."""
    return DEFAULT_MODEL.restore_punctuation(text)


def restore_text(text: str) -> str:
    """Restore the word boundaries and the punctuation of *text*."""
    return DEFAULT_MODEL.restore(text)
